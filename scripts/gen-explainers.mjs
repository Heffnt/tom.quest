// gen-explainers.mjs — the explainer registry, generated from the files.
//
// A component explainer is `<name>.explainer.html` beside the code it
// describes (WikiTom model-of-tom/explainers.md). The page opens one through
// <Info explainer="<name>">, and `explainer` is typed ExplainerId, the union of
// every name this script finds, so naming an explainer that has no file is a
// type error. Each file becomes its own module holding the page as a string,
// imported lazily, so no bundle carries every explainer.
//
// Run `pnpm gen:explainers` after adding, editing or removing an explainer.
// app/components/frame/explainers.test.ts renders the same output in memory
// and fails when the committed files differ from it.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const OUT_DIR = "app/components/frame/explainers";
const REGISTRY = "app/components/frame/explainer-registry.generated.ts";
const SUFFIX = ".explainer.html";
const SKIP_DIRS = new Set(["node_modules", ".next", ".git", ".claude"]);

/** Every explainer file under app/, as repository-relative paths, sorted. */
export function findExplainers(root) {
  const found = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
      if (SKIP_DIRS.has(entry.name)) continue;
      const rel = path.posix.join(dir, entry.name);
      if (entry.isDirectory()) walk(rel);
      else if (entry.name.endsWith(SUFFIX)) found.push(rel);
    }
  };
  walk("app");
  return found.sort();
}

/**
 * The generated files for a list of explainers, as a map from repository path
 * to content. `files` is [{ path, html }]. An explainer's id is its file name
 * without the suffix, and its title is the page's <title>.
 */
export function renderExplainerModules(files) {
  const out = new Map();
  const entries = [];
  const seen = new Map();
  for (const { path: file, html } of files) {
    const id = path.posix.basename(file).slice(0, -SUFFIX.length);
    if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(`${file}: an explainer name is lowercase words joined by hyphens`);
    if (seen.has(id)) throw new Error(`${file}: the name "${id}" is already taken by ${seen.get(id)}`);
    seen.set(id, file);
    const title = /<title>([^<]*)<\/title>/i.exec(html)?.[1]?.trim();
    if (!title) throw new Error(`${file}: an explainer carries a <title>`);
    out.set(
      `${OUT_DIR}/${id}.generated.ts`,
      `// Generated by scripts/gen-explainers.mjs from ${file}. Do not edit.\n` +
        `const html = ${JSON.stringify(html)};\nexport default html;\n`,
    );
    entries.push({ id, title, file });
  }
  const union = entries.length ? entries.map((e) => JSON.stringify(e.id)).join(" | ") : "never";
  const rows = entries
    .map(
      (e) =>
        `  ${JSON.stringify(e.id)}: {\n    title: ${JSON.stringify(e.title)},\n` +
        `    load: () => import("./explainers/${e.id}.generated"),\n  },`,
    )
    .join("\n");
  out.set(
    REGISTRY,
    `// Generated by scripts/gen-explainers.mjs from every app/**/*${SUFFIX}. Do not edit.\n\n` +
      `export type ExplainerId = ${union};\n\n` +
      `export const EXPLAINERS: Record<ExplainerId, { title: string; load: () => Promise<{ default: string }> }> = {\n` +
      `${rows}\n};\n`,
  );
  return out;
}

function main() {
  const root = process.cwd();
  const files = findExplainers(root).map((p) => ({ path: p, html: fs.readFileSync(path.join(root, p), "utf8") }));
  const out = renderExplainerModules(files);
  fs.mkdirSync(path.join(root, OUT_DIR), { recursive: true });
  for (const name of fs.readdirSync(path.join(root, OUT_DIR))) {
    const rel = `${OUT_DIR}/${name}`;
    if (name.endsWith(".generated.ts") && !out.has(rel)) fs.rmSync(path.join(root, rel));
  }
  for (const [rel, content] of out) fs.writeFileSync(path.join(root, rel), content);
  console.log(`gen-explainers: ${files.length} explainer(s)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
